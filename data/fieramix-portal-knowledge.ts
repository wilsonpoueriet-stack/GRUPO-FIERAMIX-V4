function mentionsAny(message: string, words: string[]): boolean {
  const normalize = (value: string) =>
    value
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, " ")
      .replace(/\s+/g, " ")
      .trim();
  const normalized = normalize(message);
  return words.some((word) => normalized.includes(normalize(word)));
}

